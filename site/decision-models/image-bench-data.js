export function filterImageBench(data, { query = '', access = 'all', category = 'all' } = {}) {
  const q = query.trim().toLowerCase();
  return data.filter(item => {
    if (access === 'open' && item.access !== 'Open Weights') return false;
    if (access === 'closed' && item.access !== 'Closed API') return false;
    if (category === 'jev' && item.category !== 'Jev-Class Vision') return false;
    if (category === 'baseline' && item.category !== 'Baseline Multimodal') return false;
    if (category === 'highlight' && !item.highlight) return false;
    if (q) {
      const matchName = item.name.toLowerCase().includes(q);
      const matchBase = item.baseModel.toLowerCase().includes(q);
      const matchDesc = item.description.toLowerCase().includes(q);
      if (!matchName && !matchBase && !matchDesc) return false;
    }
    return true;
  });
}

export function sortImageBench(data, sortBy = 'capabilityScore', ascending = false) {
  return [...data].sort((a, b) => {
    const valA = a[sortBy];
    const valB = b[sortBy];
    if (typeof valA === 'string') {
      return ascending ? valA.localeCompare(valB) : valB.localeCompare(valA);
    }
    return ascending ? valA - valB : valB - valA;
  });
}
